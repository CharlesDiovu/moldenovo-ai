import time
import requests
import pandas as pd
from rdkit import Chem, RDLogger
RDLogger.DisableLog("rdApp.*")

TARGET = "CHEMBL203"      # change this to try another target
MAX_RECORDS = 6000        # safety cap
BASE = "https://www.ebi.ac.uk"


def get(url, params=None, tries=4):
    for i in range(tries):
        try:
            r = requests.get(url, params=params, timeout=60)
            if r.status_code == 200:
                return r.json()
            print("HTTP", r.status_code, "- retrying")
        except requests.exceptions.RequestException as e:
            print("Network problem:", str(e)[:100], "- retrying")
        time.sleep(3 * (i + 1))
    raise RuntimeError("Could not reach ChEMBL after several tries")


# 1. Confirm what the target actually is
t = get(f"{BASE}/chembl/api/data/target/{TARGET}.json")
print("TARGET:", TARGET, "|", t.get("pref_name"), "|", t.get("organism"))

# 2. Download activities that have a pChEMBL value (a standardised potency)
url = f"{BASE}/chembl/api/data/activity.json"
params = {
    "target_chembl_id": TARGET,
    "pchembl_value__isnull": "false",
    "standard_relation": "=",
    "limit": 1000,
}
rows = []
while url and len(rows) < MAX_RECORDS:
    data = get(url, params)
    for a in data.get("activities", []):
        rows.append({
            "molecule_chembl_id": a.get("molecule_chembl_id"),
            "smiles": a.get("canonical_smiles"),
            "standard_type": a.get("standard_type"),
            "pchembl_value": a.get("pchembl_value"),
            "assay_chembl_id": a.get("assay_chembl_id"),
        })
    nxt = data.get("page_meta", {}).get("next")
    url = BASE + nxt if nxt else None
    params = None  # the 'next' link already contains the parameters
    print("downloaded", len(rows), "activity records so far")

df = pd.DataFrame(rows)
print("\nRaw records:", len(df))
print("Activity types:", df["standard_type"].value_counts().to_dict())

# 3. Clean: valid SMILES, numeric potency, one row per molecule
df = df.dropna(subset=["smiles", "pchembl_value"])
df["pchembl_value"] = df["pchembl_value"].astype(float)
df["valid"] = df["smiles"].apply(lambda s: Chem.MolFromSmiles(s) is not None)
print("Invalid SMILES dropped:", int((~df["valid"]).sum()))
df = df[df["valid"]]

clean = (
    df.groupby(["molecule_chembl_id", "smiles"], as_index=False)
      .agg(pchembl_value=("pchembl_value", "median"),
           n_measurements=("pchembl_value", "size"))
)
clean = clean.sort_values("molecule_chembl_id").reset_index(drop=True)

# 4. Report
print("\nUnique molecules:", len(clean))
print("pChEMBL range:", clean["pchembl_value"].min(), "to", clean["pchembl_value"].max())
print("Median:", clean["pchembl_value"].median())
print("\nFirst 8 rows:")
print(clean.head(8).to_string(index=False))

clean.to_csv("chembl_series.csv", index=False)

